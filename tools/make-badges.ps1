# Renders the tray day badges at the exact sizes Windows asks for, so the shell
# never has to downscale a 32 px canvas (which destroys Devanagari at 16–20 px).
# ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$fontName = 'Nirmala UI'
foreach ($candidate in @('Nirmala UI', 'Nirmala', 'Mangal', 'Segoe UI')) {
    $test = [System.Drawing.Font]::new($candidate, 12)
    if ($test.Name -eq $candidate) { $fontName = $candidate; $test.Dispose(); break }
    $test.Dispose()
}

# size -> (font px, tile padding px, corner radius px)
$variants = @(
    @{ Size = 16; Font = 11.0; Pad = 0.5; Radius = 3.5 },
    @{ Size = 20; Font = 14.0; Pad = 1.0; Radius = 4.4 },
    @{ Size = 24; Font = 17.0; Pad = 1.0; Radius = 5.3 },
    @{ Size = 32; Font = 22.0; Pad = 1.0; Radius = 7.0 }
)

function New-BadgePath([single]$x, [single]$y, [single]$w, [single]$h, [single]$r) {
    $p = [System.Drawing.Drawing2D.GraphicsPath]::new()
    $d = $r * 2
    $p.AddArc($x, $y, $d, $d, 180, 90)
    $p.AddArc($x + $w - $d, $y, $d, $d, 270, 90)
    $p.AddArc($x + $w - $d, $y + $h - $d, $d, $d, 0, 90)
    $p.AddArc($x, $y + $h - $d, $d, $d, 90, 90)
    $p.CloseFigure()
    $p
}

foreach ($variant in $variants) {
    $size = $variant.Size
    $dir = "assets\badges\b$size"
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    for ($day = 1; $day -le 32; $day++) {
        $text = -join (([string]$day).ToCharArray() | ForEach-Object { [char](0x0966 + [int][string]$_) })
        $bmp = [System.Drawing.Bitmap]::new($size, $size, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
        $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
        $g.Clear([System.Drawing.Color]::Transparent)

        $pad = [single]$variant.Pad
        $path = New-BadgePath $pad $pad ($size - 2 * $pad) ($size - 2 * $pad) ([single]$variant.Radius)
        $brush = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::FromArgb(255, 185, 20, 32))
        $g.FillPath($brush, $path)

        $font = [System.Drawing.Font]::new($fontName, [single]$variant.Font, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
        $fmt = [System.Drawing.StringFormat]::new()
        $fmt.Alignment = [System.Drawing.StringAlignment]::Center
        $fmt.LineAlignment = [System.Drawing.StringAlignment]::Center
        $fmt.FormatFlags = [System.Drawing.StringFormatFlags]::NoClip
        $rect = [System.Drawing.RectangleF]::new(-1, 0, ($size + 2), $size)
        $g.DrawString($text, $font, [System.Drawing.Brushes]::White, $rect, $fmt)

        $path.Dispose(); $brush.Dispose(); $font.Dispose(); $fmt.Dispose(); $g.Dispose()
        $bmp.Save((Join-Path (Get-Location) ("$dir\badge-{0:D2}.png" -f $day)), [System.Drawing.Imaging.ImageFormat]::Png)
        $bmp.Dispose()
    }
}

"badges: $((Get-ChildItem assets\badges -Recurse -Filter *.png | Measure-Object).Count) files in b16/b20/b24/b32"

# Emit the Rust table so the host never guesses a path at compile time.
$lines = @()
$lines += '// @generated by tools/make-badges.ps1 - do not edit.'
$lines += '//! Per-DPI tray badges, embedded at exact tray sizes.'
$lines += ''
$lines += 'pub const SIZES: [u32; 4] = [16, 20, 24, 32];'
$lines += ''
$lines += 'const FILES: [[&[u8]; 32]; 4] = ['
foreach ($size in 16, 20, 24, 32) {
    $lines += '    ['
    for ($day = 1; $day -le 32; $day++) {
        $lines += ('        include_bytes!("../../../assets/badges/b{0}/badge-{1:D2}.png"),' -f $size, $day)
    }
    $lines += '    ],'
}
$lines += '];'
$lines += ''
$tail = @'
fn index_for(scale: f64) -> usize {
    if scale >= 1.75 {
        3
    } else if scale >= 1.4 {
        2
    } else if scale >= 1.2 {
        1
    } else {
        0
    }
}

/// Pixel size of the asset used at this scale.
pub fn size_for(scale: f64) -> u32 {
    SIZES[index_for(scale)]
}

/// Pick the asset that matches the window scale, never a downscaled one.
pub fn image(day: u8, scale: f64) -> tauri::image::Image<'static> {
    let day_index = day.clamp(1, 32) as usize - 1;
    tauri::image::Image::from_bytes(FILES[index_for(scale)][day_index]).expect("embedded badge")
}
'@
$lines += ($tail -split "`n")
Set-Content -Path 'crates\host\src\badges.rs' -Value $lines -Encoding ASCII
"wrote crates\host\src\badges.rs"